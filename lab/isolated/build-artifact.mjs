import {build} from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
const output=process.argv[2];
if(!output||!path.isAbsolute(output))throw Error('Provide an absolute isolated artifact directory');
await fs.mkdir(output,{recursive:true});
const built=await build({entryPoints:['lab/src/main.ts'],bundle:true,platform:'node',format:'cjs',target:'node22',tsconfig:'lab/tsconfig.runtime.json',outfile:path.join(output,'lab.cjs'),metafile:true,external:['better-sqlite3','*.png','*.glb']});
if(Object.keys(built.metafile.inputs).some(p=>p.includes('node_modules/react-native/')))throw Error('React Native leaked into server artifact');
await fs.cp('lab/src/static',path.join(output,'static'),{recursive:true});
await fs.mkdir(path.join(output,'ml'),{recursive:true});
await fs.copyFile('lab/scripts/gtfs_stop_service.py',path.join(output,'gtfs_stop_service.py'));
await fs.copyFile('lab/ml/service.py',path.join(output,'ml/service.py'));
await fs.copyFile('lab/ml/research_motion_features.py',path.join(output,'ml/research_motion_features.py'));
await fs.copyFile('lab/isolated/requirements-candidate.txt',path.join(output,'ml/requirements-candidate.txt'));
await fs.writeFile(path.join(output,'build-inputs.json'),JSON.stringify(Object.keys(built.metafile.inputs),null,2));
console.log(`${Object.keys(built.metafile.inputs).length} code inputs; native better-sqlite3 is the only runtime npm dependency`);
